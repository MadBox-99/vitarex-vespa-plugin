<h3>
	EGYÉB SPORTÁGI RENDELKEZÉSEK
</h3>
	
<p><ul>
	<li>Győzelemért 3 pont, döntetlenért 1 pont, vereségért 0 pont jár.</li>
	<li>Azonos pontszerzés esetén az alábbi sorrend dönt:</li>
	<li>gólkülönbség,</li>
	<li>több rúgott gól,</li>
	<li>egymás ellen játszott mérkőzés eredménye,</li>
	<li>sorsolás.</li>
	<li>Egyenes kieséses mérkőzéseken döntetlen esetén a továbbjutást 3-3 büntetővel kell eldönteni. Büntetőt a mérkőzésre benevezett játékosok mindegyike rúghat. Amennyiben az első körben nem dől el a továbbjutás, a büntetőket az első hibáig kell folytatni. Ebben az esetben már bármelyik játékos rúghatja a büntetőt úgy, hogy azonos csapatból ugyanaz a játékos egymás után nem végezhet el két büntetőt.</li>
	<li>A mérkőzések szabályos kézilabda pályán (20x40 m-es), kézilabda kapukkal (2x3 m-es) kerülnek megrendezésre. A pálya talaja bármilyen lehet (füves, salakos, bitumenes, földes). A mérkőzések játékideje 2x10 perc futóórával. A várakozási idő 5 perc. Játékos létszám 5+1 fő.</li>
	<li>A mérkőzéseket 5-ös méretű labdával kell lejátszani. Tornacipő és gumistoplis labdarúgó cipő használata egyaránt engedélyezett. A mérkőzés megkezdéséhez legalább 4 játékos jelenléte szükséges, ebből 1 játékos a kapus.</li>
	<li>Játékost cserélni csak a saját térfélen lehet. Szabálytalan csere esetén sárga lap és közvetett szabadrúgás következik. A játékos-cserét nem kell bejelenteni, kivéve a kapuscserét. „Repülő cserék” (amikor a labda játékban van) korlátlan mennyiségben hajthatók végre. A cserejátékos csak akkor léphet pályára, ha a lecserélt játékos már az oldalvonalon kívül van. Szabálytalan csere esetén bírói figyelmeztetés és közvetett szabadrúgás jár.</li>
	<li>Az oldalvonalon túlra jutott labda játékba hozása nemcsak kézzel, hanem lábbal is engedélyezett (a vonalról vagy a vonalon kívülről). Bedobásból, berúgásból közvetlenül gólt nem lehet elérni. A partdobást, partrúgást a védekező játékos nem zavarhatja.</li>
	<li>Becsúszni tilos!</li>
	<li>A büntetőrúgást 7 m-ről kell elvégezni.</li>
	<li>Az alapvonalat elhagyott labdát a kapus kézzel hozza játékba. A labda akkor kerül játékba, ha a büntetőterületet elhagyja. A kapusról ill. a védekező játékosról az alapvonalon túlra jutó labda szögletrúgást eredményez. A kapus a hazaadást kézzel nem foghatja meg.</li>
	<li>A játékvezetők sárga és piros lapot alkalmaznak. A kiállítás időtartama 2 perc vagy végleges. Végleges kiállítást kell alkalmazni kirívóan súlyos sportszerűtlenség (pl. ellenfél megütése, leköpése, a játékvezető súlyos megsértése stb.) esetén. Két perces kiállítás esetén a játékos visszajöhet, véglegesen kiállított játékos helyett két perc elteltével másik játékos beállhat. Egy játékos egy mérkőzésen kétszer kaphat 2 perces kiállítást, a második után végleg kiáll, majd a két perces büntetés letelte után másik játékos állhat be helyette. A végleg kiállított játékos automatikusan kizáródik a következő mérkőzésből, de a versenybizottság az eset súlyosságától függően hosszabb eltiltást is adhat.</li>
</ul></p>

